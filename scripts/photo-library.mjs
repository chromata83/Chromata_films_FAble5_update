// Rebuilds js/photo-library.js: the list of the site's own photographs that the back office (Tools > custom quote) offers as ready-made pictures.
// Run:  node scripts/photo-library.mjs
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const img = path.join(root, "assets", "img");
const skip = new Set(["logos", "planner-logos", "awards", "testimonials", "blockbusters", "film-cards", "contact", "gallery", "heroes", "journal-thumbs", "real-weddings", "landing", "studio", "press-room"]);
const lib = {};
for (const d of fs.readdirSync(img, { withFileTypes: true })) {
  if (!d.isDirectory() || skip.has(d.name)) continue;
  const files = fs.readdirSync(path.join(img, d.name)).filter((f) => /\.(jpe?g|webp)$/i.test(f) && !/[\s"'<>]/.test(f) && !/cutout|logo|mark/i.test(f)).sort();
  if (files.length) lib[d.name] = files;
}
const out = "/* Generated by scripts/photo-library.mjs: the site's own photographs, by folder of assets/img (used by the back office quote builder). */\r\nwindow.CQ_LIBRARY = " + JSON.stringify(lib) + ";\r\n";
fs.writeFileSync(path.join(root, "js", "photo-library.js"), out);
console.log(Object.keys(lib).length + " folders, " + Object.values(lib).reduce((n, a) => n + a.length, 0) + " pictures");
